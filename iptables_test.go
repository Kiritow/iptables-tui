func TestSplitArgs(t *testing.T) {
	cases := []struct {
		in   string
		want []string
	}{
		{`-p tcp --dport 22 -j ACCEPT`, []string{"-p", "tcp", "--dport", "22", "-j", "ACCEPT"}},
		{`-m comment --comment "user c" -j DROP`, []string{"-m", "comment", "--comment", "user c", "-j", "DROP"}},
		{`--comment "a \"q\" \\ b"`, []string{"--comment", `a "q" \ b`}},
		{`--log-prefix 'x y'  -j  LOG`, []string{"--log-prefix", "x y", "-j", "LOG"}},
		{`--comment ""`, []string{"--comment", ""}},
		{`--comment "中文 注释"`, []string{"--comment", "中文 注释"}},
		{``, nil},
	}
	for _, c := range cases {
		got, err := splitArgs(c.in)
		if err != nil {
			t.Fatalf("splitArgs(%q): %v", c.in, err)
		}
		if !reflect.DeepEqual(got, c.want) {
			t.Errorf("splitArgs(%q) = %q, want %q", c.in, got, c.want)
		}
		if back, _ := splitArgs(joinArgs(got)); !reflect.DeepEqual(back, got) && len(got) > 0 {
			t.Errorf("round trip of %q gave %q", got, back)
		}
	}
	if _, err := splitArgs(`--comment "oops`); err == nil {
		t.Error("expected error for unterminated quote")
	}
}

const sample = `# Generated by iptables-save v1.8.11 (nf_tables) on Sat Oct 31 00:35:56 2026
*filter
:INPUT DROP [10:1000]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:MYCHAIN - [0:0]
[5:6] -A INPUT -p tcp -m tcp --dport 22 -m comment --comment "user c" -j ACCEPT
[0:0] -A INPUT -s 1.2.3.4/32 -j MYCHAIN
[1:2] -A INPUT -m comment --comment iptui-disabled-abcd
[0:0] -A INPUT -m comment --comment iptui-disabled-gone
[0:0] -A INPUT
[0:0] -A MYCHAIN -j REJECT --reject-with icmp-port-unreachable
COMMIT
# Completed on Sat Oct 31 00:35:56 2026
# Warning: iptables-legacy tables present, use iptables-legacy-save to see them
`

func TestParseSave(t *testing.T) {
	tables, warns, err := parseSave(sample)
	if err != nil {
		t.Fatal(err)
	}
	if len(warns) != 1 {
		t.Errorf("warnings = %q", warns)
	}
	attachStore(tables, map[string]*DisabledEntry{
		"abcd": {ID: "abcd", Args: []string{"-p", "udp", "-j", "MYCHAIN"}},
	})
	normalize(tables)
	f := tables["filter"]
	in := f.Chain("INPUT")
	if in.Policy != "DROP" || in.Pkts != 10 || len(in.Rules) != 5 {
		t.Fatalf("INPUT = %+v", in)
	}
	r := in.Rules[0]
	if r.Pkts != 5 || r.Bytes != 6 || r.Target != "ACCEPT" || r.Disabled {
		t.Errorf("rule 1 = %+v", r)
	}
	if r.MatchText != `-p tcp -m tcp --dport 22 -m comment --comment "user c"` {
		t.Errorf("match text = %q", r.MatchText)
	}
	if d := in.Rules[2]; !d.Disabled || d.Entry == nil || d.Target != "MYCHAIN" || d.Num != 3 {
		t.Errorf("disabled rule = %+v", d)
	}
	if d := in.Rules[3]; !d.Disabled || d.Entry != nil || d.Spec != nil {
		t.Errorf("orphan placeholder = %+v", d)
	}
	if e := in.Rules[4]; e.Raw != "" || len(e.Args) != 0 {
		t.Errorf("empty rule = %+v", e)
	}
	my := f.Chain("MYCHAIN")
	// the disabled jump must not count as a kernel reference
	if my.Builtin || my.Refs != 1 || len(my.RefBy) != 1 || my.Rules[0].TargetOpts != "--reject-with icmp-port-unreachable" {
		t.Errorf("MYCHAIN = %+v", my)
	}
	if nat := tables["nat"]; nat == nil || nat.Loaded || len(nat.Chains) != 4 || !nat.Chains[0].Virtual {
		t.Errorf("nat = %+v", nat)
	}
}

