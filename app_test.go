func TestSaveCounters(t *testing.T) {
	dir := t.TempDir()
	bin := filepath.Join(dir, "fake-save")
	if err := os.WriteFile(bin, []byte("#!/bin/sh\necho \":INPUT ACCEPT [12:345]\"\necho \"args:$*\"\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	a := newApp(options{fam: V4}, &Backend{Family: V4, SaveBin: bin}, &Store{})

	save := func(toggles int) string {
		t.Helper()
		out := filepath.Join(dir, "rules.v4")
		os.Remove(out)
		a.actSave()
		for i := 0; i < toggles; i++ {
			a.handleKey(Key{Code: KeyCtrl, Rune: 't'})
		}
		a.edit.Reset(out, nil)
		a.handleKey(Key{Code: KeyEnter})
		j := <-a.jobs
		if _, err := j.fn(j.be); err != nil {
			t.Fatal(err)
		}
		a.busy, a.mutBusy = 0, 0
		b, err := os.ReadFile(out)
		if err != nil {
			t.Fatal(err)
		}
		return strings.TrimSpace(string(b))
	}

	a.actSave()
	if a.mode != modePrompt || !strings.Contains(a.promptLabel, "(no counters)") {
		t.Fatalf("default: mode=%v label=%q", a.mode, a.promptLabel)
	}
	before := a.edit.Value()
	a.handleKey(Key{Code: KeyCtrl, Rune: 't'})
	if !strings.Contains(a.promptLabel, "(with counters)") || a.edit.Value() != before {
		t.Errorf("after Ctrl-T: label=%q value=%q", a.promptLabel, a.edit.Value())
	}
	a.handleKey(Key{Code: KeyEsc})

	if got := save(0); got != ":INPUT ACCEPT\nargs:" {
		t.Errorf("default save ran with %q", got)
	}
	if got := save(1); got != ":INPUT ACCEPT [12:345]\nargs:-c" {
		t.Errorf("save with counters ran with %q", got)
	}
	if got := save(2); got != ":INPUT ACCEPT\nargs:" {
		t.Errorf("toggled twice ran with %q", got)
	}
	// the toggle belongs to the save prompt only
	a.startPrompt("x: ", "", nil, nil)
	if a.promptKey != nil || a.promptHints != nil {
		t.Error("prompt hooks leak into the next prompt")
	}
}

func TestStripChainCounters(t *testing.T) {
	in := "# Generated by iptables-save v1.8.11\n*filter\n:INPUT DROP [123:4567]\n:FORWARD ACCEPT [0:0]\n" +
		":my-chain - [0:0]\n-A INPUT -m comment --comment \"[1:2]\" -j my-chain\n" +
		":odd [x:y]\nCOMMIT\n*nat\n:OUTPUT ACCEPT [9:9]"
	want := "# Generated by iptables-save v1.8.11\n*filter\n:INPUT DROP\n:FORWARD ACCEPT\n" +
		":my-chain -\n-A INPUT -m comment --comment \"[1:2]\" -j my-chain\n" +
		":odd [x:y]\nCOMMIT\n*nat\n:OUTPUT ACCEPT"
	if got := stripChainCounters(in); got != want {
		t.Errorf("got\n%s\nwant\n%s", got, want)
	}
}
